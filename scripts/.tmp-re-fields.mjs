const expectedParent = (id) =>
  staticIds.includes(id) ? 'dom:re-static' : decompileIds.includes(id) ? 'dom:re-decompile' : null;

function assert(cond, msg) {
  if (!cond) {
    console.error(`✗ ${msg}`);
    process.exit(1);
  }
}

// ---- 长度与安全字符检查 ----
const problems = [];
for (const id of [...staticIds, ...decompileIds]) {
  const c = C[id];
  assert(c, `内容表缺 ${id}`);
  const dl = c.detail.length;
  const pl = c.principle.length;
  const n = c.procedure.length;
  console.log(`${String(dl).padStart(3)}  ${String(pl).padStart(3)}  ${n} 步  ${id}`);
  if (dl > 400) problems.push(`${id} detail ${dl} > 400`);
  if (pl > 300) problems.push(`${id} principle ${pl} > 300`);
  if (n < 3 || n > 8) problems.push(`${id} procedure ${n} 步，要求 3-8`);
  for (const [field, text] of [['detail', c.detail], ['principle', c.principle]]) {
    if (!text.trim()) problems.push(`${id} ${field} 为空`);
    if (text.includes(': ')) problems.push(`${id} ${field} 含 ASCII ": "`);
    if (text.trimStart().startsWith('#')) problems.push(`${id} ${field} 以 # 开头`);
    if (text !== text.trim()) problems.push(`${id} ${field} 首尾有空白`);
  }
  c.procedure.forEach((s, i) => {
    if (!s.trim()) problems.push(`${id} procedure 第 ${i + 1} 条为空`);
    if (s.includes(': ')) problems.push(`${id} procedure 第 ${i + 1} 条含 ASCII ": "`);
    if (s !== s.trim()) problems.push(`${id} procedure 第 ${i + 1} 条首尾有空白`);
  });
}
if (problems.length) {
  console.error('✗ 内容不合规：\n  ' + problems.join('\n  '));
  process.exit(1);
}

// ---- 定位并插入 ----
const original = fs.readFileSync(FILE, 'utf8');
const origLines = original.split('\n');
const headAt = origLines.findIndex((l) => l.startsWith('- id:'));
assert(headAt > 0, '找不到首个 - id: 行');

const starts = [];
origLines.forEach((line, i) => {
  if (line.startsWith('- id: ')) starts.push({ id: line.slice(6).trim(), line: i });
});

// 每个目标块的 parent 校验
const insertions = []; // {at: 插入到该行号之前, lines: []}
for (const id of [...staticIds, ...decompileIds]) {
  const idx = starts.findIndex((s) => s.id === id);
  assert(idx >= 0, `找不到条目 ${id}`);
  const start = starts[idx].line;
  const end = idx + 1 < starts.length ? starts[idx + 1].line : origLines.length;
  const block = origLines.slice(start, end);

  const parentLines = block.filter((l) => l.startsWith('  parent:'));
  assert(parentLines.length === 1, `${id} 的 parent 行数异常`);
  assert(
    parentLines[0].trim() === `parent: ${expectedParent(id)}`,
    `${id} 的 parent 是 ${parentLines[0].trim()}，与预期不符`,
  );

  const defIdx = block.findIndex((l) => l.startsWith('  def: '));
  const cmdIdx = block.findIndex((l) => l === '  commands:');
  const pitIdx = block.findIndex((l) => l === '  pitfalls:');
  assert(defIdx >= 0, `${id} 找不到 def 行`);
  assert(cmdIdx >= 0, `${id} 找不到 commands 行`);
  assert(pitIdx >= 0, `${id} 找不到 pitfalls 行`);
  assert(pitIdx > cmdIdx, `${id} pitfalls 未在 commands 之后`);

  // 已有字段不得重复
  for (const key of ['  detail:', '  principle:', '  procedure:']) {
    assert(!block.some((l) => l.startsWith(key)), `${id} 已存在 ${key.trim()} 字段`);
  }

  const c = C[id];
  insertions.push({
    at: start + defIdx + 1,
    who: id,
    lines: [`  detail: ${c.detail}`, `  principle: ${c.principle}`],
  });
  insertions.push({
    at: start + pitIdx,
    who: id,
    lines: ['  procedure:', ...c.procedure.map((s) => `  - ${s}`)],
  });
}

// 自下而上应用，行号不失效
const outLines = origLines.slice();
const applied = [];
insertions
  .sort((a, b) => b.at - a.at)
  .forEach((ins) => {
    assert(ins.at > headAt, `插入点落在文件头注释之前：${ins.who}`);
    outLines.splice(ins.at, 0, ...ins.lines);
    applied.push(ins);
  });

// 回放校验：把插入的行原样删掉必须与原文逐行相同
const insertedText = new Set(applied.flatMap((i) => i.lines));
const rebuilt = outLines.filter((l) => !insertedText.has(l));
const rebuiltText = rebuilt.join('\n');
// 同一行文本可能同时存在于原文（例如空行），用行数比对兜底
assert(
  rebuilt.length === origLines.length,
  `回放行数不一致：${rebuilt.length} vs ${origLines.length}`,
);
const outText = outLines.join('\n');

if (process.argv.includes('--check')) {
  console.log('检查模式，不写文件');
} else {
  fs.writeFileSync(FILE, outText);
  console.log(`✓ 已写入 ${FILE}`);
}

// ---- 结构校验 ----
const after = parseYaml(outText);
const before = parseYaml(execSync(`git show HEAD:${FILE}`, { encoding: 'utf8' }));
assert(Array.isArray(after), 'YAML 顶层不是数组');
assert(after.length === 48, `条目数 ${after.length} != 48`);
assert(after.length === before.length, '条目数与 HEAD 不一致');

const beforeById = new Map(before.map((x) => [x.id, x]));
const afterById = new Map(after.map((x) => [x.id, x]));
const targets = new Set([...staticIds, ...decompileIds]);

for (const [id, oldNode] of beforeById) {
  const node = afterById.get(id);
  assert(node, `HEAD 中的 ${id} 丢了`);
  const extra = Object.keys(node).filter((k) => !(k in oldNode));
  const missing = Object.keys(oldNode).filter((k) => !(k in node));
  assert(missing.length === 0, `${id} 丢了字段 ${missing.join(',')}`);
  if (targets.has(id)) {
    assert(
      extra.sort().join(',') === 'detail,principle,procedure',
      `${id} 新增字段异常：${extra.join(',')}`,
    );
    // 已有字段逐字相同
    for (const k of Object.keys(oldNode)) {
      assert(
        JSON.stringify(oldNode[k]) === JSON.stringify(node[k]),
        `${id} 的已有字段 ${k} 被改动`,
      );
    }
    assert(typeof node.detail === 'string' && node.detail.length <= 400, `${id} detail 长度`);
    assert(typeof node.principle === 'string' && node.principle.length <= 300, `${id} principle 长度`);
    assert(Array.isArray(node.procedure) && node.procedure.length >= 3 && node.procedure.length <= 8, `${id} procedure 条数`);
    // 顺序：def → detail → principle → 之后其他字段；procedure 在 commands 之后、pitfalls 之前
    const keys = Object.keys(node);
    const di = keys.indexOf('def');
    assert(keys[di + 1] === 'detail' && keys[di + 2] === 'principle', `${id} detail/principle 未紧跟 def`);
    const ci = keys.indexOf('commands');
    assert(keys[ci + 1] === 'procedure', `${id} procedure 未紧跟 commands`);
  } else {
    assert(extra.length === 0, `${id} 不在目标集合却被改了`);
    assert(JSON.stringify(oldNode) === JSON.stringify(node), `${id} 内容被改动`);
  }
}

// 文件头注释逐字保留
const newHead = outLines.findIndex((l) => l.startsWith('- id:'));
assert(
  outLines.slice(0, newHead).join('\n') === origLines.slice(0, headAt).join('\n'),
  '文件头注释被改动',
);
console.log(`✓ 条目 ${after.length} 条；目标 ${targets.size} 条全部补齐；其余 ${after.length - targets.size} 条与 HEAD 逐字段一致`);
console.log(`✓ 文件头注释 ${newHead} 行逐字保留（原 ${headAt} 行）`);
